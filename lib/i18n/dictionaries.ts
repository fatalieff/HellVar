type DictionaryLoader = () => Promise<Dictionary>;

const loaders: Record<Locale, DictionaryLoader> = {
  az: () => import("./dictionaries/az").then((m) => m.default),
  en: () => import("./dictionaries/en").then((m) => m.default),
  tr: () => import("./dictionaries/tr").then((m) => m.default),
  ru: () => import("./dictionaries/ru").then((m) => m.default),
};

export async function getDictionary(locale: Locale): Promise<Dictionary> {
  return (loaders[locale] ?? loaders[defaultLocale])();
}
